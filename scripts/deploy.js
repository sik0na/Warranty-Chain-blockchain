// Deploys WarrantyChain and saves the address + ABI so the website knows how to talk to the contract.
//   Local:   npm run deploy
//   Sepolia: SERVICE_CENTER=0x... npm run deploy:sepolia
const { ethers, artifacts, network } = require("hardhat");
const fs = require("fs");
const path = require("path");

// Public RPC the website uses to read data (never put a private API key here, the website is public)
const PUBLIC_RPC = {
  localhost: "http://127.0.0.1:8545",
  sepolia: "https://ethereum-sepolia-rpc.publicnode.com",
};

async function main() {
  const signers = await ethers.getSigners();
  if (signers.length === 0) {
    throw new Error("No deployer wallet. Run: npx hardhat vars set DEPLOYER_PRIVATE_KEY");
  }
  const shop = signers[0]; // the deployer becomes the shop

  // Locally Hardhat account #1 is the service center.
  // On a public network you choose it with SERVICE_CENTER=0x...
  let serviceCenterAddress;
  if (network.name === "localhost") {
    serviceCenterAddress = signers[1].address;
  } else {
    serviceCenterAddress = process.env.SERVICE_CENTER;
    if (!serviceCenterAddress || !ethers.isAddress(serviceCenterAddress)) {
      throw new Error("Set the service center wallet, e.g. SERVICE_CENTER=0xABC... npm run deploy:sepolia");
    }
  }

  console.log("Deploying to", network.name, "from", shop.address, "...");
  const WarrantyChain = await ethers.getContractFactory("WarrantyChain");
  const contract = await WarrantyChain.connect(shop).deploy(serviceCenterAddress);
  await contract.waitForDeployment();

  const address = await contract.getAddress();
  const receipt = await contract.deploymentTransaction().wait();
  const chainId = Number((await ethers.provider.getNetwork()).chainId);

  console.log("WarrantyChain deployed to:", address);
  console.log("Shop:          ", shop.address);
  console.log("Service center:", serviceCenterAddress);
  if (network.name === "sepolia") {
    console.log("See it on Etherscan: https://sepolia.etherscan.io/address/" + address);
  }

  // Write a small JS file the frontend loads with a <script> tag
  const artifact = await artifacts.readArtifact("WarrantyChain");
  const output =
    "// This file is generated by scripts/deploy.js - do not edit by hand\n" +
    "const CHAIN_ID = " + chainId + ";\n" +
    "const RPC_URL = " + JSON.stringify(PUBLIC_RPC[network.name]) + ";\n" +
    "const DEPLOY_BLOCK = " + receipt.blockNumber + ";\n" +
    "const CONTRACT_ADDRESS = " + JSON.stringify(address) + ";\n" +
    "const CONTRACT_ABI = " + JSON.stringify(artifact.abi, null, 2) + ";\n";

  const filePath = path.join(__dirname, "..", "frontend", "contract-config.js");
  fs.writeFileSync(filePath, output);
  console.log("Saved contract info to frontend/contract-config.js");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
